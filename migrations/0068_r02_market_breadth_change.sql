COMMENT ON COLUMN stock.source_market_breadth_change_days.common_source_count IS '前后来源证券代码交集数量，单位为只。';
COMMENT ON COLUMN stock.source_market_breadth_change_days.eligible_count_before IS '前态市场宽度可评价证券数，单位为只。';
COMMENT ON COLUMN stock.source_market_breadth_change_days.eligible_count_target IS '目标态市场宽度可评价证券数，单位为只。';
COMMENT ON COLUMN stock.source_market_breadth_change_days.common_eligible_count IS '前后可评价证券代码交集数量，单位为只。';
