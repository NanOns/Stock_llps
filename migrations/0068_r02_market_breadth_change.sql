-- R02-CLOSE-02：固化已存BaoStock QFQ市场宽度的相邻会话变化。

CREATE TABLE stock.source_market_breadth_change_days (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    before_session date NOT NULL,
    target_session date NOT NULL,
    before_source_capture_id bigint REFERENCES stock.source_captures(capture_id),
    target_source_capture_id bigint NOT NULL REFERENCES stock.source_captures(capture_id),
    before_calendar_id text,
    target_calendar_id text NOT NULL,
    before_calendar_revision text,
    target_calendar_revision text NOT NULL,
    before_contract_version text,
    target_contract_version text NOT NULL,
    before_price_coordinate text,
    target_price_coordinate text NOT NULL CHECK (target_price_coordinate='FORWARD_ADJUSTED'),
    comparison_status text NOT NULL CHECK (comparison_status IN ('COMPARABLE','NOT_COMPARABLE','NOT_COMPUTED','INCOMPLETE','UNKNOWN')),
    reason_code text,
    source_sets_equal boolean NOT NULL,
    eligible_sets_equal boolean NOT NULL,
    unknown_sets_equal boolean NOT NULL,
    unknown_reason_mismatch_count integer NOT NULL CHECK (unknown_reason_mismatch_count>=0),
    source_count_before integer NOT NULL CHECK (source_count_before>=0),
    source_count_target integer NOT NULL CHECK (source_count_target>0),
    common_source_count integer NOT NULL CHECK (common_source_count>=0),
    eligible_count_before integer NOT NULL CHECK (eligible_count_before>=0),
    eligible_count_target integer NOT NULL CHECK (eligible_count_target>=0),
    common_eligible_count integer NOT NULL CHECK (common_eligible_count>=0),
    unknown_count_before integer NOT NULL CHECK (unknown_count_before>=0),
    unknown_count_target integer NOT NULL CHECK (unknown_count_target>=0),
    breadth_before_numerator numeric(100,0),
    breadth_before_denominator numeric(100,0),
    breadth_target_numerator numeric(100,0),
    breadth_target_denominator numeric(100,0),
    breadth_delta_numerator numeric(100,0),
    breadth_delta_denominator numeric(100,0),
    breadth_direction text CHECK (breadth_direction IN ('UP','DOWN','UNCHANGED')),
    improved_symbol_count integer NOT NULL CHECK (improved_symbol_count>=0),
    deteriorated_symbol_count integer NOT NULL CHECK (deteriorated_symbol_count>=0),
    unchanged_symbol_count integer NOT NULL CHECK (unchanged_symbol_count>=0),
    unknown_symbol_count integer NOT NULL CHECK (unknown_symbol_count>=0),
    source_set_sha256_before char(64) CHECK (source_set_sha256_before IS NULL OR source_set_sha256_before ~ '^[0-9a-f]{64}$'),
    source_set_sha256_target char(64) NOT NULL CHECK (source_set_sha256_target ~ '^[0-9a-f]{64}$'),
    eligible_set_sha256_before char(64) CHECK (eligible_set_sha256_before IS NULL OR eligible_set_sha256_before ~ '^[0-9a-f]{64}$'),
    eligible_set_sha256_target char(64) NOT NULL CHECK (eligible_set_sha256_target ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT source_market_breadth_change_order_ck CHECK (before_session<target_session),
    CONSTRAINT source_market_breadth_change_denominator_ck CHECK (
        (breadth_before_numerator IS NULL AND breadth_before_denominator IS NULL)
        OR (breadth_before_numerator IS NOT NULL AND breadth_before_denominator>0)
    ),
    CONSTRAINT source_market_breadth_change_target_denominator_ck CHECK (
        (breadth_target_numerator IS NULL AND breadth_target_denominator IS NULL)
        OR (breadth_target_numerator IS NOT NULL AND breadth_target_denominator>0)
    ),
    CONSTRAINT source_market_breadth_change_delta_denominator_ck CHECK (
        (breadth_delta_numerator IS NULL AND breadth_delta_denominator IS NULL)
        OR (breadth_delta_numerator IS NOT NULL AND breadth_delta_denominator>0)
    ),
    CONSTRAINT source_market_breadth_change_scope_ck CHECK (
        common_source_count<=LEAST(source_count_before,source_count_target)
        AND common_eligible_count<=LEAST(eligible_count_before,eligible_count_target)
        AND eligible_count_before<=source_count_before
        AND eligible_count_target<=source_count_target
        AND unknown_count_before=source_count_before-eligible_count_before
        AND unknown_count_target=source_count_target-eligible_count_target
    ),
    CONSTRAINT source_market_breadth_change_state_ck CHECK (
        (comparison_status='COMPARABLE'
         AND reason_code IS NULL
         AND before_source_capture_id=target_source_capture_id
         AND before_calendar_id=target_calendar_id
         AND before_calendar_revision=target_calendar_revision
         AND before_contract_version=target_contract_version
         AND before_price_coordinate='FORWARD_ADJUSTED'
         AND target_price_coordinate='FORWARD_ADJUSTED'
         AND source_sets_equal AND eligible_sets_equal AND unknown_sets_equal
         AND unknown_reason_mismatch_count=0
         AND source_count_before=source_count_target
         AND common_source_count=source_count_target
         AND eligible_count_before=eligible_count_target
         AND common_eligible_count=eligible_count_target
         AND improved_symbol_count+deteriorated_symbol_count+unchanged_symbol_count=common_eligible_count
         AND unknown_symbol_count=unknown_count_target
         AND breadth_before_denominator IS NOT NULL
         AND breadth_target_denominator IS NOT NULL
         AND breadth_delta_denominator IS NOT NULL
         AND breadth_direction IS NOT NULL)
        OR
        (comparison_status<>'COMPARABLE'
         AND reason_code IS NOT NULL AND btrim(reason_code)<>''
         AND breadth_delta_numerator IS NULL
         AND breadth_delta_denominator IS NULL
         AND breadth_direction IS NULL)
    ),
    CONSTRAINT source_market_breadth_change_pair_uq UNIQUE (
        before_session,target_session,target_source_capture_id,
        target_calendar_revision,target_contract_version
    )
);

COMMENT ON TABLE stock.source_market_breadth_change_days IS '保存相邻官方会话已存BaoStock QFQ市场宽度的typed变化结果；只有同一捕获、日历、算法、来源集合和可评价集合完全一致时才给出差值。';
COMMENT ON COLUMN stock.source_market_breadth_change_days.id IS '相邻会话市场宽度变化事实的数据库代理编号。';
