COMMENT ON COLUMN stock.source_market_breadth_change_days.source_sets_equal IS '前后来源证券代码集合是否逐代码完全相等。';
COMMENT ON COLUMN stock.source_market_breadth_change_days.eligible_sets_equal IS '前后可评价证券代码集合是否逐代码完全相等。';
COMMENT ON COLUMN stock.source_market_breadth_change_days.unknown_sets_equal IS '前后UNKNOWN证券代码集合是否逐代码完全相等。';
COMMENT ON COLUMN stock.source_market_breadth_change_days.unknown_reason_mismatch_count IS '前后共同UNKNOWN证券的主原因码不一致只数；严格可比较时必须为零。';
