COMMENT ON COLUMN stock.source_sector_pulse_cohort_reason_facts.quality_status IS '受影响关系的状态：UNKNOWN、NOT_COMPUTED、NOT_DUE或INCOMPLETE。';
COMMENT ON COLUMN stock.source_sector_pulse_cohort_reason_facts.reason_code IS '对应业务合同的具名失败、缺失或未到期原因码。';
