CREATE TABLE stock.source_sector_pulse_cohort_group_facts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    t0_session date NOT NULL,
    research_cutoff date NOT NULL,
    t0_source_package_id bigint NOT NULL,
    t0_source_capture_id bigint NOT NULL,
    t0_profile_revision text NOT NULL,
    snapshot_id bigint NOT NULL,
    pulse_algorithm_contract text NOT NULL,
    cohort_contract text NOT NULL,
    followup_contract text NOT NULL,
    board_kind text NOT NULL,
    cohort_axis text NOT NULL,
    cohort_state text NOT NULL,
    horizon_sessions smallint NOT NULL,
    target_session date,
    target_source_package_id bigint,
    target_source_capture_id bigint,
    calendar_id text NOT NULL,
    calendar_revision text NOT NULL,
    group_status text NOT NULL,
    board_relation_denominator integer NOT NULL,
    observed_board_count integer NOT NULL,
    unknown_board_count integer NOT NULL,
    not_computed_board_count integer NOT NULL,
    not_due_board_count integer NOT NULL,
    incomplete_board_count integer NOT NULL,
    fixed_member_denominator_sum bigint NOT NULL,
    evaluable_fixed_member_denominator_sum bigint NOT NULL,
    observed_member_count_sum bigint NOT NULL,
    unknown_member_count_sum bigint NOT NULL,
    positive_board_count integer,
    nonpositive_board_count integer,
    mean_return_numerator numeric,
    mean_return_denominator numeric,
    median_return_numerator numeric,
    median_return_denominator numeric,
    minimum_return_numerator numeric,
    minimum_return_denominator numeric,
    maximum_return_numerator numeric,
    maximum_return_denominator numeric,
    research_mode text NOT NULL,
    membership_mode text NOT NULL,
    price_coordinate text NOT NULL,
    source_time_quality text NOT NULL,
    source_clock_role text NOT NULL,
    source_available_at timestamp with time zone,
    formal_rotation_state text NOT NULL,
    recorded_at timestamp with time zone NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT source_sector_pulse_cohort_group_business_uq UNIQUE (
        t0_session,
        research_cutoff,
        t0_source_package_id,
        t0_source_capture_id,
        t0_profile_revision,
        snapshot_id,
        pulse_algorithm_contract,
        cohort_contract,
        followup_contract,
        board_kind,
        cohort_axis,
        cohort_state,
        horizon_sessions,
        calendar_id,
        calendar_revision
    ),
    CONSTRAINT source_sector_pulse_cohort_group_identity_ck CHECK (
        t0_session <= research_cutoff
        AND t0_source_package_id > 0
        AND t0_source_capture_id > 0
        AND t0_profile_revision <> ''
        AND snapshot_id > 0
        AND pulse_algorithm_contract = 'SOURCE_CROSS_PERIOD_PULSE_R1'
        AND cohort_contract = 'SOURCE_SECTOR_PULSE_COHORT_OUTCOMES_R1'
        AND followup_contract = 'SOURCE_SECTOR_PULSE_FOLLOWUP_CLOSE_R1'
        AND board_kind IN ('INDUSTRY', 'CONCEPT')
        AND cohort_axis IN ('PULSE_STATE', 'ADJACENT_TRANSITION')
        AND (
            (cohort_axis = 'PULSE_STATE' AND cohort_state IN ('TRUE', 'FALSE', 'UNKNOWN'))
            OR (
                cohort_axis = 'ADJACENT_TRANSITION'
                AND cohort_state IN (
                    'PULSE_APPEARED',
                    'PULSE_PERSISTED',
                    'PULSE_CEASED',
                    'PULSE_NOT_PRESENT_BOTH',
                    'PULSE_TRANSITION_UNKNOWN',
                    'NO_STORED_TRANSITION'
                )
            )
        )
        AND horizon_sessions IN (1, 3, 5)
        AND (
            target_session IS NULL
            OR (target_session > t0_session AND target_session <= research_cutoff)
        )
        AND (
            (target_source_package_id IS NULL AND target_source_capture_id IS NULL)
            OR (
                target_source_package_id IS NOT NULL
                AND target_source_capture_id IS NOT NULL
                AND target_source_package_id > 0
                AND target_source_capture_id > 0
            )
        )
        AND calendar_id <> ''
        AND calendar_revision <> ''
        AND group_status IN (
            'AVAILABLE', 'UNKNOWN', 'NOT_COMPUTED', 'NOT_DUE', 'INCOMPLETE', 'NO_GROUP_MEMBERS'
        )
        AND research_mode = 'NON_PIT_RETROSPECTIVE'
        AND membership_mode = 'CURRENT_MEMBERSHIP_RETROSPECTIVE_NON_PIT'
        AND price_coordinate = 'RAW_UNADJUSTED'
        AND source_time_quality <> ''
        AND source_clock_role <> ''
        AND formal_rotation_state = 'NOT_EVALUATED'
    ),
    CONSTRAINT source_sector_pulse_cohort_group_counts_ck CHECK (
        board_relation_denominator >= 0
        AND observed_board_count >= 0
        AND unknown_board_count >= 0
        AND not_computed_board_count >= 0
        AND not_due_board_count >= 0
        AND incomplete_board_count >= 0
        AND observed_board_count + unknown_board_count + not_computed_board_count
            + not_due_board_count + incomplete_board_count = board_relation_denominator
        AND fixed_member_denominator_sum >= 0
        AND evaluable_fixed_member_denominator_sum >= 0
        AND evaluable_fixed_member_denominator_sum <= fixed_member_denominator_sum
        AND observed_member_count_sum >= 0
        AND unknown_member_count_sum >= 0
        AND observed_member_count_sum + unknown_member_count_sum
            = evaluable_fixed_member_denominator_sum
        AND (
            (board_relation_denominator = 0 AND group_status = 'NO_GROUP_MEMBERS')
            OR (board_relation_denominator > 0 AND group_status <> 'NO_GROUP_MEMBERS')
        )
    ),
    CONSTRAINT source_sector_pulse_cohort_group_distribution_ck CHECK (
        (
            observed_board_count > 0
            AND positive_board_count IS NOT NULL
            AND nonpositive_board_count IS NOT NULL
            AND positive_board_count >= 0
            AND nonpositive_board_count >= 0
            AND positive_board_count + nonpositive_board_count = observed_board_count
            AND mean_return_numerator IS NOT NULL
            AND mean_return_denominator IS NOT NULL
            AND mean_return_denominator > 0
            AND median_return_numerator IS NOT NULL
            AND median_return_denominator IS NOT NULL
            AND median_return_denominator > 0
            AND minimum_return_numerator IS NOT NULL
            AND minimum_return_denominator IS NOT NULL
            AND minimum_return_denominator > 0
            AND maximum_return_numerator IS NOT NULL
            AND maximum_return_denominator IS NOT NULL
            AND maximum_return_denominator > 0
        )
        OR (
            observed_board_count = 0
            AND positive_board_count IS NULL
            AND nonpositive_board_count IS NULL
            AND mean_return_numerator IS NULL
            AND mean_return_denominator IS NULL
            AND median_return_numerator IS NULL
            AND median_return_denominator IS NULL
            AND minimum_return_numerator IS NULL
            AND minimum_return_denominator IS NULL
            AND maximum_return_numerator IS NULL
            AND maximum_return_denominator IS NULL
        )
    )
);

