CREATE TABLE stock.source_sector_pulse_cohort_reason_facts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort_group_fact_id bigint NOT NULL
        REFERENCES stock.source_sector_pulse_cohort_group_facts(id) ON DELETE CASCADE,
    reason_scope text NOT NULL,
    quality_status text NOT NULL,
    reason_code text NOT NULL,
    board_relation_count integer NOT NULL,
    recorded_at timestamp with time zone NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT source_sector_pulse_cohort_reason_business_uq UNIQUE (
        cohort_group_fact_id,
        reason_scope,
        quality_status,
        reason_code
    ),
    CONSTRAINT source_sector_pulse_cohort_reason_scope_ck CHECK (
        reason_scope IN ('OUTCOME', 'GROUPING')
        AND quality_status IN (
            'UNKNOWN', 'NOT_COMPUTED', 'NOT_DUE', 'INCOMPLETE'
        )
        AND reason_code <> ''
        AND board_relation_count > 0
    )
);

CREATE INDEX source_sector_pulse_cohort_reason_read_idx
    ON stock.source_sector_pulse_cohort_reason_facts (
        cohort_group_fact_id,
        reason_scope,
        quality_status
    );

