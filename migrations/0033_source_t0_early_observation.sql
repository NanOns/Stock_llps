CREATE TABLE stock.source_t0_early_observation_facts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id bigint NOT NULL REFERENCES stock.source_research_enrollments(id),
    target_session date NOT NULL,
    source_package_id bigint NOT NULL REFERENCES stock.source_packages(source_package_id),
    source_capture_id bigint NOT NULL,
    source_symbol text NOT NULL,
    d0_fact_id bigint REFERENCES stock.source_d0_launch_day_facts(id),
    rule_fact_id bigint REFERENCES stock.source_rule_evaluations(id),
    seed_fact_id bigint NOT NULL REFERENCES stock.source_pool_seed_day_facts(id),
    membership_snapshot_id bigint REFERENCES stock.tdx_sector_source_snapshots(snapshot_id),
    catalog_id bigint REFERENCES stock.tdx_sector_catalog(id),
    board_kind text,
    board_native_id text,
    board_context_key text NOT NULL,
    membership_status text NOT NULL,
    membership_mode text NOT NULL,
    pulse_fact_id bigint REFERENCES stock.source_sector_cross_period_pulse_facts(id),
    pulse_status text NOT NULL,
    pulse_state text NOT NULL,
    pulse_transition_id bigint REFERENCES stock.source_sector_pulse_adjacent_transitions(id),
    transition_status text NOT NULL,
    transition_state text NOT NULL,
    transition_reason_codes text[] NOT NULL DEFAULT '{}',
    snapshot_member_count integer,
    source_pool_member_count integer,
    rps5_quality text NOT NULL,
    rps5_reason text,
    rps5_rank_first integer,
    rps5_rank_last integer,
    rps5_valid_member_count integer NOT NULL,
    rps5_unknown_member_count integer NOT NULL,
    rps5_out_of_source_pool_member_count integer,
    rps5_position text NOT NULL,
    rps20_quality text NOT NULL,
    rps20_reason text,
    rps20_rank_first integer,
    rps20_rank_last integer,
    rps20_valid_member_count integer NOT NULL,
    rps20_unknown_member_count integer NOT NULL,
    rps20_out_of_source_pool_member_count integer,
    rps20_position text NOT NULL,
    relative_position text NOT NULL,
    alignment_state text NOT NULL,
    research_case text NOT NULL,
    support_codes text[] NOT NULL DEFAULT '{}',
    counter_codes text[] NOT NULL DEFAULT '{}',
    unknown_codes text[] NOT NULL DEFAULT '{}',
    next_check_code text NOT NULL,
    hypothesis_version text NOT NULL,
    evidence_revision_key text NOT NULL,
    research_mode text NOT NULL,
    price_coordinate text NOT NULL,
    recorded_at timestamp with time zone NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT source_t0_early_symbol_ck
        CHECK (source_symbol ~ '^(SH|SZ)\.[0-9]{6}$'),
    CONSTRAINT source_t0_early_membership_ck
        CHECK (
            (membership_status = 'MAPPED' AND membership_snapshot_id IS NOT NULL
             AND catalog_id IS NOT NULL AND board_kind IN ('INDUSTRY', 'CONCEPT')
             AND board_native_id IS NOT NULL)
            OR
            (membership_status <> 'MAPPED' AND membership_snapshot_id IS NULL
             AND catalog_id IS NULL AND board_kind IS NULL AND board_native_id IS NULL)
        ),
    CONSTRAINT source_t0_early_membership_status_ck
        CHECK (membership_status IN ('MAPPED', 'UNKNOWN', 'NO_STORED_FACT')),
    CONSTRAINT source_t0_early_membership_mode_ck
        CHECK (membership_mode = 'CURRENT_MEMBERSHIP_RETROSPECTIVE_NON_PIT'),
    CONSTRAINT source_t0_early_pulse_status_ck
        CHECK (pulse_status IN ('AVAILABLE', 'NOT_COMPUTED', 'UNKNOWN')),
    CONSTRAINT source_t0_early_pulse_state_ck
        CHECK (pulse_state IN ('TRUE', 'FALSE', 'UNKNOWN', 'NOT_COMPUTED')),
    CONSTRAINT source_t0_early_transition_status_ck
        CHECK (transition_status IN ('AVAILABLE', 'NOT_COMPUTED', 'UNKNOWN')),
    CONSTRAINT source_t0_early_transition_state_ck
        CHECK (transition_state IN (
            'PULSE_APPEARED', 'PULSE_PERSISTED', 'PULSE_CEASED',
            'PULSE_NOT_PRESENT_BOTH', 'PULSE_TRANSITION_UNKNOWN', 'NOT_COMPUTED'
        )),
    CONSTRAINT source_t0_early_reason_count_ck
        CHECK (cardinality(transition_reason_codes) <= 8),
    CONSTRAINT source_t0_early_member_counts_ck
        CHECK (
            (snapshot_member_count IS NULL OR snapshot_member_count >= 0)
            AND (source_pool_member_count IS NULL OR source_pool_member_count >= 0)
            AND (snapshot_member_count IS NULL OR source_pool_member_count IS NULL
                 OR source_pool_member_count <= snapshot_member_count)
        ),
    CONSTRAINT source_t0_early_rps5_quality_ck
        CHECK (rps5_quality IN ('OBSERVED', 'UNKNOWN', 'BAD_VALUE', 'NOT_APPLICABLE', 'NOT_COMPUTED')),
    CONSTRAINT source_t0_early_rps5_counts_ck
        CHECK (rps5_valid_member_count >= 0 AND rps5_unknown_member_count >= 0
               AND (rps5_out_of_source_pool_member_count IS NULL
                    OR rps5_out_of_source_pool_member_count >= 0)
               AND ((rps5_rank_first IS NULL AND rps5_rank_last IS NULL)
                    OR (rps5_rank_first > 0 AND rps5_rank_last >= rps5_rank_first
                        AND rps5_rank_last <= rps5_valid_member_count))),
    CONSTRAINT source_t0_early_rps5_position_ck
        CHECK (rps5_position IN ('FRONT_HALF', 'BACK_HALF', 'MIDPOINT_TIE', 'UNKNOWN', 'NOT_COMPUTED')),
    CONSTRAINT source_t0_early_rps20_quality_ck
        CHECK (rps20_quality IN ('OBSERVED', 'UNKNOWN', 'BAD_VALUE', 'NOT_APPLICABLE', 'NOT_COMPUTED')),
    CONSTRAINT source_t0_early_rps20_counts_ck
        CHECK (rps20_valid_member_count >= 0 AND rps20_unknown_member_count >= 0
               AND (rps20_out_of_source_pool_member_count IS NULL
                    OR rps20_out_of_source_pool_member_count >= 0)
               AND ((rps20_rank_first IS NULL AND rps20_rank_last IS NULL)
                    OR (rps20_rank_first > 0 AND rps20_rank_last >= rps20_rank_first
                        AND rps20_rank_last <= rps20_valid_member_count))),
    CONSTRAINT source_t0_early_rps20_position_ck
        CHECK (rps20_position IN ('FRONT_HALF', 'BACK_HALF', 'MIDPOINT_TIE', 'UNKNOWN', 'NOT_COMPUTED')),
    CONSTRAINT source_t0_early_relative_position_ck
        CHECK (relative_position IN ('BOTH_FRONT_HALF', 'BOTH_BACK_HALF', 'MIXED', 'MIDPOINT_TIE', 'UNKNOWN', 'NOT_COMPUTED')),
    CONSTRAINT source_t0_early_alignment_ck
        CHECK (alignment_state IN ('SUPPORT', 'CONFLICT', 'MIXED', 'NEUTRAL', 'UNKNOWN')),
    CONSTRAINT source_t0_early_case_ck
        CHECK (research_case IN (
            'D0_PULSE_APPEARED_FRONT', 'D0_PULSE_TRUE_FRONT', 'D0_PULSE_TRUE_BACK',
            'D0_PULSE_TRUE_MIXED', 'D0_PULSE_FALSE_CONFLICT', 'PULSE_TRUE_BACK',
            'PULSE_UNKNOWN', 'NO_BOARD_MAPPING', 'BOARD_CONTEXT'
        )),
    CONSTRAINT source_t0_early_support_codes_ck
        CHECK (support_codes <@ ARRAY[
            'D0_FALSE_TO_TRUE', 'PULSE_TRUE', 'PULSE_APPEARED', 'PULSE_PERSISTED',
            'RPS5_FRONT_HALF', 'RPS20_FRONT_HALF'
        ]::text[] AND cardinality(support_codes) <= 6),
    CONSTRAINT source_t0_early_counter_codes_ck
        CHECK (counter_codes <@ ARRAY[
            'PULSE_FALSE', 'PULSE_CEASED', 'RPS5_BACK_HALF', 'RPS20_BACK_HALF',
            'RPS5_RPS20_MIXED'
        ]::text[] AND cardinality(counter_codes) <= 5),
    CONSTRAINT source_t0_early_unknown_codes_ck
        CHECK (unknown_codes <@ ARRAY[
            'MEMBERSHIP_UNKNOWN', 'PULSE_CURRENT_UNKNOWN', 'PULSE_NOT_COMPUTED',
            'PULSE_TRANSITION_NOT_COMPUTED', 'RPS5_UNKNOWN', 'RPS20_UNKNOWN'
        ]::text[] AND cardinality(unknown_codes) <= 6),
    CONSTRAINT source_t0_early_next_check_ck
        CHECK (next_check_code IN (
            'WAIT_FOR_NEXT_STORED_SESSION', 'CHECK_NEXT_PULSE_TRANSITION',
            'CHECK_RPS_POSITION_NEXT_SESSION', 'VERIFY_CONFLICT_RESOLUTION',
            'WAIT_FOR_MISSING_CONTEXT'
        )),
    CONSTRAINT source_t0_early_version_ck
        CHECK (hypothesis_version = 'EARLY_BOARD_RELATIVE_T0_R1'),
    CONSTRAINT source_t0_early_research_mode_ck
        CHECK (research_mode = 'NON_PIT_EXPLORATORY'),
    CONSTRAINT source_t0_early_price_coordinate_ck
        CHECK (price_coordinate = 'RAW_UNADJUSTED'),
    CONSTRAINT source_t0_early_context_revision_uq
        UNIQUE (enrollment_id, hypothesis_version, board_context_key, evidence_revision_key)
);

CREATE INDEX source_t0_early_session_symbol_idx
    ON stock.source_t0_early_observation_facts (target_session, source_package_id, source_capture_id, source_symbol);
CREATE INDEX source_t0_early_enrollment_idx
    ON stock.source_t0_early_observation_facts (enrollment_id, recorded_at DESC);

